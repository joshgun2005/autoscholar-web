/**
 * Find pdflatex binary on the system (macOS TeX Live / MacTeX)
 */
function findPdflatex(augmentedPath: string): string | null {
  const candidates = [
    '/Library/TeX/texbin/pdflatex',
    '/usr/local/texlive/2025/bin/universal-darwin/pdflatex',
    '/usr/local/texlive/2024/bin/universal-darwin/pdflatex',
    '/usr/local/texlive/2025/bin/x86_64-darwin/pdflatex',
    '/usr/local/texlive/2024/bin/x86_64-darwin/pdflatex',
    '/usr/texbin/pdflatex',
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  // Try PATH
  const dirs = augmentedPath.split(':');
  for (const dir of dirs) {
    const p = path.join(dir, 'pdflatex');
    if (fs.existsSync(p)) return p;
  }
  return null;
}

function findBibtex(augmentedPath: string): string | null {
  const candidates = [
    '/Library/TeX/texbin/bibtex',
    '/usr/local/texlive/2025/bin/universal-darwin/bibtex',
    '/usr/local/texlive/2024/bin/universal-darwin/bibtex',
    '/usr/local/texlive/2025/bin/x86_64-darwin/bibtex',
    '/usr/local/texlive/2024/bin/x86_64-darwin/bibtex',
    '/usr/texbin/bibtex',
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return c;
  }
  const dirs = augmentedPath.split(':');
  for (const dir of dirs) {
    const p = path.join(dir, 'bibtex');
    if (fs.existsSync(p)) return p;
  }
  return null;
}

/**
 * Build the augmented PATH with TeX Live directories
 */
function getTexPath(): string {
  const texBinPaths = [
    '/Library/TeX/texbin',
    '/usr/local/texlive/2025/bin/universal-darwin',
    '/usr/local/texlive/2024/bin/universal-darwin',
    '/usr/texbin',
  ];
  return `${texBinPaths.join(':')}:${process.env.PATH || '/usr/bin:/bin'}`;
}

