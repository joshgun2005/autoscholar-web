/**
 * Generate a complete academic research paper as PDF using pdflatex + bibtex.
 *
 * Compilation pipeline:
 *   pdflatex → bibtex → pdflatex → pdflatex  (4-pass for citations)
 * If no bibtex_entries, uses 2-pass pdflatex only.
 */
export async function generateResearchPaper(input: ResearchPaperInput): Promise<ResearchPaperResult> {
  const augmentedPath = getTexPath();
  const pdflatex = findPdflatex(augmentedPath);
  if (!pdflatex) {
    return {
      success: false,
      error: 'pdflatex not found. Install MacTeX (brew install --cask mactex) or TeX Live.',
    };
  }

  // Create temp work directory
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), 'vq_research_'));
  const texFile = 'paper.tex';
  const texPath = path.join(workDir, texFile);
  const env = { ...process.env, PATH: augmentedPath };

  try {
    // 1. Save figures as PNG files with validation (skip empty/blank images)
    const savedFigureIds: string[] = [];
    if (input.figures && input.figures.length > 0) {
      console.log(`📊 [ResearchPaper] Received ${input.figures.length} figures to embed`);
      for (const fig of input.figures) {
        const figPath = path.join(workDir, `fig_${fig.id}.png`);
        // Strip data URL prefix if present (Python executor sends pure base64, but handle both cases)
        const base64Data = fig.base64.replace(/^data:image\/[^;]+;base64,/, '');

        if (!base64Data || base64Data.length < 50) {
          console.warn(`⚠️ [ResearchPaper] Figure ${fig.id}: base64 data is empty or too small (${base64Data?.length || 0} chars) — skipping`);
          continue;
        }

        try {
          const buffer = Buffer.from(base64Data, 'base64');

          // Check if the image is essentially blank (single-colour PNG)
          // by sampling pixel data from the raw PNG buffer.
          if (isBlankPng(buffer)) {
            console.warn(`⚠️ [ResearchPaper] Figure ${fig.id}: image is blank/empty — skipping`);
            continue;
          }

          fs.writeFileSync(figPath, buffer);
          const stat = fs.statSync(figPath);
          savedFigureIds.push(fig.id);
          console.log(`  ✓ Figure ${fig.id}: saved ${stat.size} bytes → ${figPath}`);
        } catch (figErr) {
          console.error(`  ✗ Figure ${fig.id}: failed to save — ${(figErr as Error).message}`);
        }
      }
      console.log(`📊 [ResearchPaper] Successfully saved ${savedFigureIds.length}/${input.figures.length} figures: [${savedFigureIds.join(', ')}]`);
    } else {
      console.log(`📊 [ResearchPaper] No figures provided for embedding`);
    }

    // 2. Write BibTeX file if provided
    const hasBib = !!input.bibtex_entries;
    if (hasBib) {
      fs.writeFileSync(path.join(workDir, 'references.bib'), input.bibtex_entries!, 'utf-8');
    }

    // 3. Build the LaTeX document based on template
    const template = input.template || 'article';
    let fullLatex: string;
    switch (template) {
      case 'working_paper':
        fullLatex = buildWorkingPaperTemplate(input);
        break;
      case 'econometrica':
        fullLatex = buildEconometricaTemplate(input);
        break;
      default:
        fullLatex = buildArticleTemplate(input);
    }

    // 4. Count and replace {{FIG:id}} placeholders
    const placeholderMatches = fullLatex.match(/\{\{FIG:(\w+)\}\}/g) || [];
    console.log(`📊 [ResearchPaper] Found ${placeholderMatches.length} figure placeholders in LaTeX: ${placeholderMatches.join(', ')}`);
    console.log(`📊 [ResearchPaper] Available figure files: ${savedFigureIds.map(id => `fig_${id}.png`).join(', ')}`);

    let replacedCount = 0;
    let missingFigureCount = 0;
    let figCounter = 0;

    // Smart replacement: detect if {{FIG:id}} is already inside a \begin{figure} environment
    // If so, only replace with \includegraphics (Claude wrote the caption/label).
    // If bare, wrap in a full figure environment with a generic caption.
    // Also handles \begin{figure*} and \begin{figure}[htbp] variants.
    fullLatex = fullLatex.replace(/\{\{FIG:(\w+)\}\}/g, (match, id, offset) => {
      const figFile = `fig_${id}.png`;

      // Look back ~400 chars for \begin{figure} or \begin{figure*} without a closing \end{figure}
      const lookback = fullLatex.substring(Math.max(0, offset - 400), offset);
      const lastBeginFig = Math.max(
        lookback.lastIndexOf('\\begin{figure}'),
        lookback.lastIndexOf('\\begin{figure*}'),
        lookback.lastIndexOf('\\begin{figure}['),
      );
      const lastEndFig = Math.max(
        lookback.lastIndexOf('\\end{figure}'),
        lookback.lastIndexOf('\\end{figure*}'),
      );
      const isInsideFigureEnv = lastBeginFig !== -1 && lastBeginFig > lastEndFig;

      if (!fs.existsSync(path.join(workDir, figFile))) {
        missingFigureCount++;
        console.warn(`  ✗ {{FIG:${id}}} not found — available: [${savedFigureIds.join(', ')}]`);
        if (isInsideFigureEnv) {
          // Inside a figure environment — remove the entire environment to avoid empty figure
          // Return a comment; the sanitizer later will handle orphaned \caption/\label
          return `% [Figure ${id} omitted — image not generated in this session]`;
        }
        return `% [Figure ${id} omitted — not generated in this session]`;
      }

      replacedCount++;
      figCounter++;

      if (isInsideFigureEnv) {
        // Claude already wrote \begin{figure}, \caption, \label — just provide the image
        console.log(`  ✓ {{FIG:${id}}} inside existing figure env → \\includegraphics only`);
        return `\\includegraphics[width=\\linewidth]{${figFile}}`;
      }

      // Bare placeholder — wrap with full figure environment and generic caption
      console.log(`  ✓ {{FIG:${id}}} bare → full figure environment with caption`);
      return `\\begin{figure}[H]\n\\centering\n\\includegraphics[width=\\linewidth]{${figFile}}\n\\caption{Figure ${figCounter}}\n\\label{fig:${id}}\n\\end{figure}`;
    });

    // 5. If NO placeholders were found but figures exist, auto-inject at end of document
    if (placeholderMatches.length === 0 && savedFigureIds.length > 0) {
      console.warn(`⚠️ [ResearchPaper] No {{FIG:N}} placeholders in LaTeX but ${savedFigureIds.length} figures available — auto-injecting as appendix`);

      // Build a figures appendix section
      let appendixLatex = '\n\n\\newpage\n\\section*{Figures}\n\\addcontentsline{toc}{section}{Figures}\n\n';
      for (const figId of savedFigureIds) {
        const figFile = `fig_${figId}.png`;
        const figNum = parseInt(figId) + 1;
        appendixLatex += `\\begin{figure}[H]\n\\centering\n\\includegraphics[width=0.95\\linewidth]{${figFile}}\n\\caption{Figure ${figNum}}\n\\label{fig:${figId}}\n\\end{figure}\n\n`;
        replacedCount++;
      }

      // Insert before \end{document}
      fullLatex = fullLatex.replace(/\\end\{document\}/, appendixLatex + '\\end{document}');
    }

    // 4b. Remove empty figure environments (figure was omitted but wrapper remains)
    // Matches \begin{figure}[...] ... % [Figure N omitted ...] ... \end{figure} with no \includegraphics
    fullLatex = fullLatex.replace(
      /\\begin\{figure\*?\}(?:\[[^\]]*\])?\s*(?:\\centering\s*)?%\s*\[Figure \d+ omitted[^\]]*\][\s%]*(?:\\caption\{[^}]*\}\s*)?(?:\\label\{[^}]*\}\s*)?\\end\{figure\*?\}/g,
      (match) => {
        console.log(`  🧹 Removed empty figure environment: ${match.substring(0, 60)}...`);
        return '% [Empty figure environment removed]';
      }
    );

    console.log(`📊 [ResearchPaper] Figure summary: ${replacedCount} embedded, ${missingFigureCount} missing, ${savedFigureIds.length} available`);

    // 6a. Sanitize LaTeX content (fix unclosed environments, common errors)
    fullLatex = sanitizeLatexContent(fullLatex);

    // 6b. Strip any landscape wrappers around tables (causes page breaks + vertical overflow)
    fullLatex = stripLandscapeTables(fullLatex);

    // 6c. Auto-fit wide tables: use font size reduction + adjustbox (NO landscape, NO page breaks)
    fullLatex = autoFitWideTables(fullLatex);

    // 6d. Safety wrap any remaining bare tables with adjustbox to prevent overflow
    fullLatex = safetyWrapOverflowTables(fullLatex);

    // 6. Write .tex file
    fs.writeFileSync(texPath, fullLatex, 'utf-8');

    // 6. Compile (nonstopmode — push through warnings, no -halt-on-error)
    const pdflatexCmd = `"${pdflatex}" -interaction=nonstopmode "${texFile}"`;

    const bibtexBin = hasBib ? findBibtex(augmentedPath) : null;
    if (hasBib && !bibtexBin) {
      return { success: false, error: 'bibtex not found. Install MacTeX or TeX Live.' };
    }

    const runPass = async (cmd: string, label: string, timeout = 60000) => {
      try {
        const { stderr } = await execAsync(cmd, { cwd: workDir, env, timeout });
        if (stderr) console.warn(`⚠️ [${label}] stderr: ${stderr.substring(0, 300)}`);
      } catch (err: any) {
        // pdflatex returns non-zero on warnings too — only log, don't throw
        const msg = err?.stderr || err?.message || '';
        console.warn(`⚠️ [${label}] exited with error (may still produce PDF): ${msg.substring(0, 300)}`);
      }
    };

    const runCompilation = async () => {
      if (hasBib) {
        const bibtexCmd = `"${bibtexBin}" paper`;
        // 4-pass: pdflatex → bibtex → pdflatex → pdflatex (resolves TOC + citations)
        await runPass(pdflatexCmd, 'pdflatex pass 1');
        await runPass(bibtexCmd, 'bibtex', 30000);
        await runPass(pdflatexCmd, 'pdflatex pass 2');
        await runPass(pdflatexCmd, 'pdflatex pass 3');
      } else {
        // 3-pass: pdflatex → pdflatex → pdflatex (resolves TOC + hyperref links)
        await runPass(pdflatexCmd, 'pdflatex pass 1');
        await runPass(pdflatexCmd, 'pdflatex pass 2');
        await runPass(pdflatexCmd, 'pdflatex pass 3');
      }
    };

    await runCompilation();

    // 7. Check output — if no PDF, try progressive fallbacks
    const compiledPdf = path.join(workDir, 'paper.pdf');
    if (!fs.existsSync(compiledPdf)) {
      // Fallback 1: strip newtxmath/Libertinus (font issues)
      console.warn('First compilation produced no PDF — retrying without custom fonts (Computer Modern fallback)');
      let fallbackLatex = fullLatex
        .replace(/\\usepackage\{newtxtext\}\n/g, '')
        .replace(/\\usepackage\{newtxmath\}\n/g, '')
        .replace(/\\usepackage\{libertinus\}\n/g, '')
        .replace(/\\usepackage\{libertinust1math\}[^\n]*\n/g, '')
        .replace(/\\let\\Bbbk\\relax[^\n]*\n/g, '')
        .replace(/\\let\\openbox\\relax[^\n]*\n/g, '');
      fs.writeFileSync(texPath, fallbackLatex, 'utf-8');
      await runCompilation();

      if (!fs.existsSync(compiledPdf)) {
        // Fallback 2: also strip microtype + lettrine (known problematic packages)
        console.warn('Second compilation failed — stripping microtype, lettrine, tikz title page');
        fallbackLatex = fallbackLatex
          .replace(/\\usepackage\[[\s\S]*?\]\{microtype\}[\s\S]*?\\SetTracking[^\n]*\n/g, '')
          .replace(/\\usepackage\{lettrine\}[\s\S]*?\\renewcommand\{\\DefaultLhang\}[^\n]*/g, '')
          .replace(/\\usepackage\{marginnote\}[^\n]*/g, '')
          .replace(/\\renewcommand\*?\{\\marginfont\}[^\n]*/g, '');
        fs.writeFileSync(texPath, fallbackLatex, 'utf-8');
        await runCompilation();
      }

      if (!fs.existsSync(compiledPdf)) {
        // Fallback 3: parse log for specific LaTeX errors and try to auto-fix
        const logPath = path.join(workDir, 'paper.log');
        if (fs.existsSync(logPath)) {
          const logContent = fs.readFileSync(logPath, 'utf-8');
          const errorLines = logContent.split('\n').filter(l => l.startsWith('!'));
          console.warn(`Fallback 3: ${errorLines.length} LaTeX errors found: ${errorLines.slice(0, 5).join(' | ')}`);

          let patched = fallbackLatex;
          let didPatch = false;

          // Fix "Undefined control sequence" — comment out the offending line
          for (const errLine of errorLines) {
            const undefinedMatch = errLine.match(/Undefined control sequence.*\\(\w+)/);
            if (undefinedMatch) {
              const badCmd = undefinedMatch[1];
              // Only auto-fix non-critical commands
              const safeToRemove = ['lettrine', 'marginnote', 'epigraph', 'rowshade'];
              if (safeToRemove.includes(badCmd)) {
                patched = patched.replace(new RegExp(`\\\\${badCmd}(\\{[^}]*\\})*`, 'g'), '');
                didPatch = true;
              }
            }
            // Fix "Missing $ inserted" — often caused by bare _ in text
            if (errLine.includes('Missing $ inserted')) {
              // Find bare underscores not in math mode or commands
              patched = patched.replace(/(?<!\\)_(?![{a-zA-Z])/g, '\\_');
              didPatch = true;
            }
            // Fix "Unicode character ... not set up for use with LaTeX"
            if (errLine.includes('Unicode character')) {
              // Strip any remaining non-ASCII non-Latin characters that pdflatex can't handle
              // This is a last-resort fallback — the sanitizeLatexContent() mapping above
              // should catch most cases, but Claude may produce rare Unicode we didn't map.
              patched = patched.replace(/[\u0370-\u03FF]/g, '?');   // Greek block
              patched = patched.replace(/[\u2200-\u22FF]/g, '?');   // Math operators block
              patched = patched.replace(/[\u2190-\u21FF]/g, '?');   // Arrows block
              patched = patched.replace(/[\u2010-\u2027]/g, '-');   // General punctuation (dashes, etc.)
              didPatch = true;
            }
          }

          if (didPatch) {
            fs.writeFileSync(texPath, patched, 'utf-8');
            await runCompilation();
          }
        }
      }
    }

    if (!fs.existsSync(compiledPdf)) {
      // Read log for diagnostics
      const logPath = path.join(workDir, 'paper.log');
      let logTail = '';
      if (fs.existsSync(logPath)) {
        const logContent = fs.readFileSync(logPath, 'utf-8');
        const errorLines = logContent.split('\n').filter(l => l.startsWith('!'));
        logTail = errorLines.length > 0
          ? errorLines.slice(0, 10).join('\n')
          : logContent.split('\n').slice(-30).join('\n');
      }
      return { success: false, error: `pdflatex ran but paper.pdf was not produced.\n${logTail}`, workDir };
    }

    // 8. Post-compilation diagnostics — check for unresolved references (??? in PDF)
    const logPath = path.join(workDir, 'paper.log');
    if (fs.existsSync(logPath)) {
      const logContent = fs.readFileSync(logPath, 'utf-8');
      const unresolvedRefs = logContent.match(/LaTeX Warning: Reference `([^']+)' on page \d+ undefined/g);
      const unresolvedCites = logContent.match(/LaTeX Warning: Citation `([^']+)' on page \d+ undefined/g);
      if (unresolvedRefs && unresolvedRefs.length > 0) {
        console.warn(`⚠️ [ResearchPaper] ${unresolvedRefs.length} unresolved \\ref{} (will show ??? in PDF):`);
        unresolvedRefs.slice(0, 10).forEach(r => console.warn(`  ${r}`));
      }
      if (unresolvedCites && unresolvedCites.length > 0) {
        console.warn(`⚠️ [ResearchPaper] ${unresolvedCites.length} unresolved \\cite{} (will show [?] in PDF):`);
        unresolvedCites.slice(0, 10).forEach(r => console.warn(`  ${r}`));
      }
      // Check for multiply-defined labels (duplicate \label{})
      const multiLabels = logContent.match(/LaTeX Warning: Label `([^']+)' multiply defined/g);
      if (multiLabels && multiLabels.length > 0) {
        console.warn(`⚠️ [ResearchPaper] ${multiLabels.length} multiply-defined \\label{} (may cause wrong references):`);
        multiLabels.slice(0, 10).forEach(r => console.warn(`  ${r}`));
      }
    }

    // 9. Copy to downloads location
    const baseName = input.filename
      ? input.filename.replace(/[^a-zA-Z0-9._-]/g, '_').replace(/\.pdf$/i, '') + '.pdf'
      : 'research_paper.pdf';
    const destPath = path.join(os.tmpdir(), `vq_${Date.now()}_${baseName}`);
    fs.copyFileSync(compiledPdf, destPath);

    // 10. Keep work directory alive for project ZIP download (caller cleans up)
    return {
      success: true,
      filepath: destPath,
      filename: baseName,
      workDir,
    };
  } catch (error) {
    // Try to read log for diagnostics
    const logPath = path.join(workDir, 'paper.log');
    let logTail = '';
    if (fs.existsSync(logPath)) {
      const logContent = fs.readFileSync(logPath, 'utf-8');
      const errorLines = logContent.split('\n').filter(l => l.startsWith('!'));
      logTail = errorLines.length > 0
        ? errorLines.slice(0, 10).join('\n')
        : logContent.split('\n').slice(-20).join('\n');
    }

    // Preserve workDir for repair loop — caller (routes.ts) will register it
    // with latexPatchManager so Claude can inspect/patch/recompile.

    return {
      success: false,
      error: `LaTeX compilation failed: ${(error as Error).message}\n${logTail}`,
      workDir,
    };
  }
}
