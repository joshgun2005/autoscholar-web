/**
 * Escape special LaTeX characters in plain text
 */
export function escapeLatex(text: string): string {
  return text
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/[&%$#_{}~^]/g, (ch) => `\\${ch}`)
    .replace(/\|/g, '\\textbar{}')
    .replace(/</g, '\\textless{}')
    .replace(/>/g, '\\textgreater{}');
}

/**
 * Sanitize LaTeX body content generated by Claude.
 * Fixes common issues that cause compilation failures.
 */
export function sanitizeLatexContent(latex: string): string {
  let out = latex;

  // 0. Replace Unicode characters that pdflatex cannot handle.
  //    Claude often outputs native Unicode Greek letters and math symbols
  //    instead of LaTeX commands. pdflatex + inputenc(utf8) only supports
  //    a Latin subset — Greek, math operators, and special symbols must be
  //    converted to their LaTeX equivalents.
  const unicodeToLatex: [RegExp, string][] = [
    // Greek lowercase
    [/α/g, '$\\alpha$'],
    [/β/g, '$\\beta$'],
    [/γ/g, '$\\gamma$'],
    [/δ/g, '$\\delta$'],
    [/ε/g, '$\\varepsilon$'],
    [/ζ/g, '$\\zeta$'],
    [/η/g, '$\\eta$'],
    [/θ/g, '$\\theta$'],
    [/ι/g, '$\\iota$'],
    [/κ/g, '$\\kappa$'],
    [/λ/g, '$\\lambda$'],
    [/μ/g, '$\\mu$'],
    [/ν/g, '$\\nu$'],
    [/ξ/g, '$\\xi$'],
    [/π/g, '$\\pi$'],
    [/ρ/g, '$\\rho$'],
    [/σ/g, '$\\sigma$'],
    [/τ/g, '$\\tau$'],
    [/υ/g, '$\\upsilon$'],
    [/φ/g, '$\\varphi$'],
    [/χ/g, '$\\chi$'],
    [/ψ/g, '$\\psi$'],
    [/ω/g, '$\\omega$'],
    // Greek uppercase
    [/Γ/g, '$\\Gamma$'],
    [/Δ/g, '$\\Delta$'],
    [/Θ/g, '$\\Theta$'],
    [/Λ/g, '$\\Lambda$'],
    [/Ξ/g, '$\\Xi$'],
    [/Π/g, '$\\Pi$'],
    [/Σ/g, '$\\Sigma$'],
    [/Φ/g, '$\\Phi$'],
    [/Ψ/g, '$\\Psi$'],
    [/Ω/g, '$\\Omega$'],
    // Math operators & symbols
    [/−/g, '$-$'],           // U+2212 minus sign
    [/×/g, '$\\times$'],     // U+00D7 multiplication sign
    [/÷/g, '$\\div$'],       // U+00F7 division sign
    [/±/g, '$\\pm$'],        // U+00B1 plus-minus
    [/∓/g, '$\\mp$'],        // U+2213 minus-plus
    [/≤/g, '$\\leq$'],       // U+2264
    [/≥/g, '$\\geq$'],       // U+2265
    [/≠/g, '$\\neq$'],       // U+2260
    [/≈/g, '$\\approx$'],    // U+2248
    [/∞/g, '$\\infty$'],     // U+221E
    [/∑/g, '$\\sum$'],       // U+2211
    [/∏/g, '$\\prod$'],      // U+220F
    [/√/g, '$\\sqrt{}$'],    // U+221A
    [/∂/g, '$\\partial$'],   // U+2202
    [/∈/g, '$\\in$'],        // U+2208
    [/∉/g, '$\\notin$'],     // U+2209
    [/∀/g, '$\\forall$'],    // U+2200
    [/∃/g, '$\\exists$'],    // U+2203
    [/→/g, '$\\rightarrow$'],// U+2192
    [/←/g, '$\\leftarrow$'], // U+2190
    [/↔/g, '$\\leftrightarrow$'], // U+2194
    [/⇒/g, '$\\Rightarrow$'],// U+21D2
    [/⇐/g, '$\\Leftarrow$'], // U+21D0
    [/∧/g, '$\\wedge$'],     // U+2227
    [/∨/g, '$\\vee$'],       // U+2228
    [/¬/g, '$\\neg$'],       // U+00AC
    [/⊂/g, '$\\subset$'],   // U+2282
    [/⊃/g, '$\\supset$'],   // U+2283
    [/∅/g, '$\\emptyset$'],  // U+2205
    [/·/g, '$\\cdot$'],      // U+00B7 middle dot
    [/°/g, '$^{\\circ}$'],   // U+00B0 degree sign
    [/′/g, '$^{\\prime}$'],  // U+2032 prime
    [/″/g, '$^{\\prime\\prime}$'], // U+2033 double prime
    // Superscript / subscript digits (common in chemical formulas, etc.)
    [/²/g, '$^{2}$'],        // U+00B2
    [/³/g, '$^{3}$'],        // U+00B3
    [/¹/g, '$^{1}$'],        // U+00B9
    // Dashes (em/en) — these are safe in T1 but let's be explicit
    [/—/g, '---'],           // U+2014 em dash
    [/–/g, '--'],            // U+2013 en dash
    // Quotes
    [/\u201C/g, "``"],            // U+201C left double quote
    [/\u201D/g, "''"],            // U+201D right double quote
    [/\u2018/g, "`"],             // U+2018 left single quote
    [/\u2019/g, "'"],             // U+2019 right single quote
    // Ellipsis
    [/…/g, '\\ldots{}'],     // U+2026
    // Misc
    [/†/g, '$\\dagger$'],    // U+2020
    [/‡/g, '$\\ddagger$'],   // U+2021
    [/•/g, '$\\bullet$'],    // U+2022
    [/™/g, '\\texttrademark{}'], // U+2122
    [/©/g, '\\textcopyright{}'], // U+00A9
    [/®/g, '\\textregistered{}'], // U+00AE
    // Additional math symbols Claude may emit
    [/∝/g, '$\\propto$'],   // U+221D proportional to
    [/∫/g, '$\\int$'],      // U+222B integral
    [/∬/g, '$\\iint$'],     // U+222C double integral
    [/∇/g, '$\\nabla$'],    // U+2207 nabla
    [/⊕/g, '$\\oplus$'],   // U+2295
    [/⊗/g, '$\\otimes$'],  // U+2297
    [/≡/g, '$\\equiv$'],    // U+2261
    [/≅/g, '$\\cong$'],     // U+2245
    [/≃/g, '$\\simeq$'],    // U+2243
    [/≫/g, '$\\gg$'],       // U+226B
    [/≪/g, '$\\ll$'],       // U+226A
    [/⊆/g, '$\\subseteq$'],// U+2286
    [/⊇/g, '$\\supseteq$'],// U+2287
    [/∪/g, '$\\cup$'],      // U+222A
    [/∩/g, '$\\cap$'],      // U+2229
    [/∘/g, '$\\circ$'],     // U+2218 ring operator
    [/⟨/g, '$\\langle$'],   // U+27E8 left angle bracket
    [/⟩/g, '$\\rangle$'],   // U+27E9 right angle bracket
    [/ℝ/g, '$\\mathbb{R}$'],// U+211D
    [/ℕ/g, '$\\mathbb{N}$'],// U+2115
    [/ℤ/g, '$\\mathbb{Z}$'],// U+2124
    [/ℚ/g, '$\\mathbb{Q}$'],// U+211A
    [/ℂ/g, '$\\mathbb{C}$'],// U+2102
    [/ℓ/g, '$\\ell$'],      // U+2113 script small l
    [/⁰/g, '$^{0}$'],       // U+2070
    [/⁴/g, '$^{4}$'],       // U+2074
    [/⁵/g, '$^{5}$'],       // U+2075
    [/⁶/g, '$^{6}$'],       // U+2076
    [/⁷/g, '$^{7}$'],       // U+2077
    [/⁸/g, '$^{8}$'],       // U+2078
    [/⁹/g, '$^{9}$'],       // U+2079
    [/⁻/g, '$^{-}$'],       // U+207B superscript minus
    [/⁺/g, '$^{+}$'],       // U+207A superscript plus
    [/₀/g, '$_{0}$'],       // U+2080 subscript 0
    [/₁/g, '$_{1}$'],       // U+2081
    [/₂/g, '$_{2}$'],       // U+2082
    [/₃/g, '$_{3}$'],       // U+2083
    [/₄/g, '$_{4}$'],       // U+2084
    [/ₙ/g, '$_{n}$'],       // U+2099
    [/ₜ/g, '$_{t}$'],       // U+209C
    [/ₓ/g, '$_{x}$'],       // U+2093 -- not standard but Claude emits it
  ];

  // Only replace Unicode chars that appear OUTSIDE of already-existing math mode ($...$)
  // to avoid double-wrapping. We first protect existing math environments, then replace,
  // then restore, then collapse adjacent $$ boundaries from adjacent replacements.

  // Step A: protect existing display math ($$...$$) with placeholders
  const displayMathBlocks: string[] = [];
  out = out.replace(/\$\$([\s\S]+?)\$\$/g, (_m, body) => {
    const idx = displayMathBlocks.length;
    displayMathBlocks.push(body);
    return `%%DISPLAYMATH_PROTECT_${idx}%%`;
  });

  // Step B: protect existing inline math ($...$) — but not currency ($123)
  const inlineMathBlocks: string[] = [];
  out = out.replace(/\$([^\$\n]+?)\$/g, (_m, body) => {
    // Skip if it looks like currency (pure digits/commas/dots)
    if (/^\s*[\d.,]+\s*$/.test(body)) return _m;
    const idx = inlineMathBlocks.length;
    inlineMathBlocks.push(body);
    return `%%INLINEMATH_PROTECT_${idx}%%`;
  });

  // Step C: protect \begin{equation}...\end{equation}, \begin{align}...\end{align}, etc.
  const mathEnvBlocks: string[] = [];
  out = out.replace(/\\begin\{(equation\*?|align\*?|gather\*?|multline\*?|split|aligned|gathered|eqnarray\*?)\}([\s\S]*?)\\end\{\1\}/g, (_m) => {
    const idx = mathEnvBlocks.length;
    mathEnvBlocks.push(_m);
    return `%%MATHENV_PROTECT_${idx}%%`;
  });

  // Step D: now replace Unicode chars in the remaining (non-math) text
  for (const [re, replacement] of unicodeToLatex) {
    out = out.replace(re, replacement);
  }

  // Step E: restore math environments (in reverse order of protection)
  out = out.replace(/%%MATHENV_PROTECT_(\d+)%%/g, (_m, idx) => mathEnvBlocks[parseInt(idx)]);
  out = out.replace(/%%INLINEMATH_PROTECT_(\d+)%%/g, (_m, idx) => `$${inlineMathBlocks[parseInt(idx)]}$`);
  out = out.replace(/%%DISPLAYMATH_PROTECT_(\d+)%%/g, (_m, idx) => `$$${displayMathBlocks[parseInt(idx)]}$$`);

  // Step F: collapse adjacent math mode boundaries from adjacent Unicode replacements:
  // $\alpha$$\beta$ → $\alpha\beta$ (but NOT $$...$$ display math)
  // Only collapse $$ that sits BETWEEN two LaTeX commands (not at line start/end)
  out = out.replace(/\$\$(?=\\[a-zA-Z])/g, '');

  // 1. Fix unmatched \begin{tabular}...\end{table} and vice versa
  //    Count environments and warn but don't break
  const envPairs: [string, RegExp, RegExp][] = [
    ['table', /\\begin\{table\}/g, /\\end\{table\}/g],
    ['table*', /\\begin\{table\*\}/g, /\\end\{table\*\}/g],
    ['figure', /\\begin\{figure\}/g, /\\end\{figure\}/g],
    ['figure*', /\\begin\{figure\*\}/g, /\\end\{figure\*\}/g],
    ['tabular', /\\begin\{tabular\}/g, /\\end\{tabular\}/g],
    ['tabular*', /\\begin\{tabular\*\}/g, /\\end\{tabular\*\}/g],
    ['tabularx', /\\begin\{tabularx\}/g, /\\end\{tabularx\}/g],
    ['landscape', /\\begin\{landscape\}/g, /\\end\{landscape\}/g],
    ['threeparttable', /\\begin\{threeparttable\}/g, /\\end\{threeparttable\}/g],
    ['adjustbox', /\\begin\{adjustbox\}/g, /\\end\{adjustbox\}/g],
  ];
  for (const [name, openRe, closeRe] of envPairs) {
    const opens = (out.match(openRe) || []).length;
    const closes = (out.match(closeRe) || []).length;
    if (opens > closes) {
      // Add missing \end{...} at the very end
      for (let i = 0; i < opens - closes; i++) {
        out += `\n\\end{${name}}`;
      }
      console.warn(`⚠️ [sanitize] Added ${opens - closes} missing \\end{${name}}`);
    }
  }

  // 2. Fix double \hline\hline → single (booktabs style prefers \midrule)
  out = out.replace(/\\hline\s*\\hline/g, '\\midrule');

  // 3. Replace raw \hline with booktabs equivalents in booktabs-style tables
  //    (only when booktabs commands are already present nearby)

  // 4. Fix common "Undefined control sequence" issues
  out = out.replace(/\\textit\s*\{/g, '\\textit{');
  out = out.replace(/\\textbf\s*\{/g, '\\textbf{');

  // 5. Escape bare % in URLs (common Claude mistake)
  out = out.replace(/(https?:\/\/[^\s}]+)(%[^0-9A-Fa-f])/g, '$1\\$2');

  // 6. Fix broken cross-references (tables/figures showing ??? in PDF).
  //    Common causes: \label before \caption, mismatched \ref/\label keys, missing \label entirely.
  {
    // 6a. Collect all \label{...} keys
    const definedLabels = new Set<string>();
    let labelMatch: RegExpExecArray | null;
    const labelRe = /\\label\{([^}]+)\}/g;
    while ((labelMatch = labelRe.exec(out)) !== null) definedLabels.add(labelMatch[1]);

    // 6b. Collect all \ref{...} and \autoref{...} keys
    const referencedLabels: string[] = [];
    let refMatch: RegExpExecArray | null;
    const refRe = /\\(?:ref|autoref|eqref|cref)\{([^}]+)\}/g;
    while ((refMatch = refRe.exec(out)) !== null) referencedLabels.push(refMatch[1]);

    // 6c. Find orphan references (referenced but never defined)
    const orphanRefs = referencedLabels.filter(r => !definedLabels.has(r));
    if (orphanRefs.length > 0) {
      const uniqueOrphans = Array.from(new Set(orphanRefs));
      console.warn(`⚠️ [sanitize] Found ${uniqueOrphans.length} orphan \\ref{} without matching \\label{}: ${uniqueOrphans.join(', ')}`);

      for (const orphan of uniqueOrphans) {
        // Try fuzzy matching: tab:1 vs tab:main_results, fig:0 vs fig:returns
        // Check if a similar label exists (same prefix, different suffix)
        const prefix = orphan.split(':')[0]; // "tab" or "fig"
        const candidates = Array.from(definedLabels).filter(l => l.startsWith(prefix + ':'));

        if (candidates.length > 0) {
          // If there's exactly one candidate with the same prefix, auto-fix
          // Otherwise, try to match by position (nth table/figure)
          const orphanIdx = orphan.match(/(\d+)/)?.[1];
          if (orphanIdx !== undefined) {
            // Match by index: \ref{tab:2} → find the 3rd \label{tab:...} in document order
            const idx = parseInt(orphanIdx);
            if (idx < candidates.length) {
              const replacement = candidates[idx];
              out = out.replace(
                new RegExp(`\\\\(ref|autoref|cref)\\{${orphan.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\}`, 'g'),
                `\\$1{${replacement}}`
              );
              console.log(`  ✓ Auto-fixed \\ref{${orphan}} → \\ref{${replacement}}`);
            }
          }
        }
      }
    }

    // 6d. Fix \label placed BEFORE \caption (LaTeX requires \label after \caption)
    //     Pattern: \label{...} ... \caption{...} inside a table/figure env → swap order
    out = out.replace(
      /(\\label\{[^}]+\})\s*\n(\s*\\caption)/g,
      (match, label, caption) => {
        console.warn(`⚠️ [sanitize] Moved \\label after \\caption (was before)`);
        return `${caption}`;
      }
    );
    // Then re-insert label after the caption's closing brace
    // Actually, better approach: ensure \label comes after \caption within table/figure envs
    out = out.replace(
      /(\\begin\{(?:table|figure)\}(?:\[[^\]]*\])?)([\s\S]*?)(\\end\{(?:table|figure)\})/g,
      (match, beginTag, body, endTag) => {
        // Check if \label appears before \caption in this environment
        const labelPos = body.search(/\\label\{/);
        const captionPos = body.search(/\\caption\{/);

        if (labelPos !== -1 && captionPos !== -1 && labelPos < captionPos) {
          // Extract the label
          const labelMatch = body.match(/\\label\{([^}]+)\}/);
          if (labelMatch) {
            // Remove label from its current position
            let fixed = body.replace(/\s*\\label\{[^}]+\}\s*/g, '\n');
            // Insert label right after the end of \caption{...}
            // Find where \caption{...} ends (matching braces)
            let braceDepth = 0;
            let captionEnd = -1;
            const capStart = fixed.indexOf('\\caption{');
            if (capStart !== -1) {
              for (let i = capStart + 9; i < fixed.length; i++) {
                if (fixed[i] === '{') braceDepth++;
                if (fixed[i] === '}') {
                  if (braceDepth === 0) { captionEnd = i + 1; break; }
                  braceDepth--;
                }
              }
              if (captionEnd !== -1) {
                fixed = fixed.substring(0, captionEnd) + `\n\\label{${labelMatch[1]}}` + fixed.substring(captionEnd);
                console.log(`  ✓ Moved \\label{${labelMatch[1]}} to after \\caption in ${beginTag.includes('table') ? 'table' : 'figure'}`);
              }
            }
            return `${beginTag}${fixed}${endTag}`;
          }
        }
        return match;
      }
    );

    // 6e. Auto-add missing \label to tables that have \caption but no \label
    let tableCounter = 0;
    out = out.replace(
      /(\\begin\{table\}(?:\[[^\]]*\])?)([\s\S]*?)(\\end\{table\})/g,
      (match, beginTag, body, endTag) => {
        tableCounter++;
        if (!body.includes('\\label{')) {
          // Find end of \caption{...} and insert \label after it
          const capMatch = body.match(/(\\caption\{[^}]*\})/);
          if (capMatch) {
            const label = `tab:auto_${tableCounter}`;
            const fixed = body.replace(capMatch[0], `${capMatch[0]}\n\\label{${label}}`);
            console.log(`  ✓ Auto-added \\label{${label}} to table without label`);
            return `${beginTag}${fixed}${endTag}`;
          }
        }
        return match;
      }
    );
  }

  // 7. Auto-split long equations that will overflow margins.
  //    Convert \begin{equation}...\end{equation} with very long content (>120 chars on a single line)
  //    to \begin{multline} or \begin{split} if they contain natural break points (=, +, -).
  out = out.replace(
    /\\begin\{equation\}(\*?)\s*([\s\S]*?)\\end\{equation\}\1/g,
    (match, star, body) => {
      const trimmed = body.trim();
      // Only act on single-line equations that are very long
      const lines = trimmed.split('\n').map((l: string) => l.trim()).filter((l: string) => l.length > 0);
      if (lines.length === 1 && trimmed.length > 120) {
        // Check if it already uses split/align/multline inside
        if (/\\\\|\\begin\{(split|aligned|multline|gathered)\}/.test(trimmed)) {
          return match; // already multi-line
        }

        // Try to split at = sign — but NOT \leq, \geq, \neq, \equiv, etc.
        // Use a negative lookbehind for common comparison operators
        const eqParts = trimmed.split(/(?<!\\[a-zA-Z])(?<![<>!])=/);
        if (eqParts.length >= 2) {
          // Use split environment: LHS &= RHS (break at =)
          const joined = eqParts.join('\\\\\n  &= ');
          console.log(`📐 [equation] Split long equation (${trimmed.length} chars) at = sign → split environment`);
          return `\\begin{equation${star}}\n\\begin{split}\n  ${joined}\n\\end{split}\n\\end{equation${star}}`;
        }

        // Fall back to multline (breaks at +/- operators, but not inside subscripts/superscripts)
        const plusParts = trimmed.split(/(?<=[^_^{])(?=\s*[+-]\s)/);
        if (plusParts.length >= 2) {
          const joined = plusParts.join('\\\\\n  ');
          console.log(`📐 [equation] Split long equation (${trimmed.length} chars) at +/- → multline`);
          return `\\begin{multline${star}}\n  ${joined}\n\\end{multline${star}}`;
        }
      }
      return match;
    }
  );

  // 7b. Fix misaligned multiline equations in align/align* environments.
  //     Ensure every line with an = sign has & before the = for proper alignment.
  out = out.replace(
    /\\begin\{(align\*?)\}([\s\S]*?)\\end\{\1\}/g,
    (match, envName, body) => {
      const lines = body.split('\\\\');
      let changed = false;

      const fixedLines = lines.map((line: string) => {
        const trimmedLine = line.trim();
        // Skip empty lines, labels, nonumber, and lines that already have &
        if (!trimmedLine || trimmedLine.startsWith('\\label') || trimmedLine.startsWith('\\nonumber')) return line;
        if (line.includes('&')) return line; // already has alignment marker

        // Find a bare = sign (not \leq, \geq, \neq, \equiv, etc.)
        // and insert & before it for alignment
        const eqMatch = line.match(/^(.*?)(?<!\\[a-zA-Z])(?<![<>!])=/);
        if (eqMatch) {
          changed = true;
          return line.replace(/(?<!\\[a-zA-Z])(?<![<>!])=/, '&=');
        }
        return line;
      });

      if (changed) {
        console.log(`📐 [align] Auto-added & alignment markers in \\begin{${envName}} environment`);
        return `\\begin{${envName}}${fixedLines.join('\\\\')}\\end{${envName}}`;
      }
      return match;
    }
  );

  return out;
}

/**
 * Count effective columns in a table body.
 * Uses both first-row ampersand count and column spec parsing.
 * Handles tabular, tabularx, tabular*, and threeparttable wrapping.
 */
export function countTableColumns(body: string): number {
  // Count from first data row (& characters) — find any tabular variant
  const tabularMatch = body.match(/\\begin\{tabular[x*]?\}(?:\s*\{[^}]*\})*\s*\{([^}]+)\}\s*(?:\\[a-z]+[^&\n]*\n)*([^\n]*&[^\n]*)/);
  let colCount = 1;
  if (tabularMatch) {
    const firstDataRow = tabularMatch[2];
    const ampersands = firstDataRow.match(/(?<!\\)&/g);
    colCount = (ampersands ? ampersands.length : 0) + 1;
  } else {
    // Fallback: find any line with & inside the body
    const anyRowMatch = body.match(/^(?!.*\\begin|.*\\end|.*\\caption|.*\\label|.*\\hline|.*\\toprule|.*\\midrule|.*\\bottomrule)(.+&.+)$/m);
    if (anyRowMatch) {
      const ampersands = anyRowMatch[1].match(/(?<!\\)&/g);
      colCount = (ampersands ? ampersands.length : 0) + 1;
    }
  }

  // Count from column spec: {lccccccr} or {p{2cm}...} or {X X l r}
  // Match the LAST brace group after \begin{tabular...} (handles tabular*{width}{cols} and tabularx{width}{cols})
  const colSpecMatches = Array.from(body.matchAll(/\\begin\{tabular[x*]?\}(?:\s*\{[^}]*\})*\s*\{([^}]+)\}/g));
  let specColCount = 0;
  if (colSpecMatches.length > 0) {
    const spec = colSpecMatches[0][1];
    // Count column-type characters: l, c, r, p, X, S, d (ignore |, @, >, <, !)
    // Also count p{...}, m{...}, b{...} as single columns
    const cleaned = spec
      .replace(/@\{[^}]*\}/g, '')    // remove @{...} inter-column specs
      .replace(/>\{[^}]*\}/g, '')    // remove >{...}
      .replace(/<\{[^}]*\}/g, '')    // remove <{...}
      .replace(/!\{[^}]*\}/g, '')    // remove !{...}
      .replace(/[|*\s]/g, '');       // remove pipes, stars, spaces
    // Count column letters (l,c,r,X,S,d) + p/m/b{...} patterns
    specColCount = (cleaned.match(/[lcCrRXSd]|[pmb]\{[^}]*\}/g) || []).length;
  }

  return Math.max(colCount, specColCount);
}

/**
 * Strip landscape wrappers around tables. Claude sometimes wraps tables in
 * \begin{landscape}...\end{landscape} which forces a page break and often
 * causes vertical overflow. We replace with inline scaling instead.
 */
export function stripLandscapeTables(latex: string): string {
  // Pattern: \begin{landscape} ... \begin{table} ... \end{table} ... \end{landscape}
  // Replace with just the table content (landscape wrapper removed).
  // Handles both table and table* environments.
  return latex.replace(
    /\\begin\{landscape\}\s*(\\begin\{table\*?\}(?:\[[^\]]*\])?[\s\S]*?\\end\{table\*?\})\s*\\end\{landscape\}/g,
    (_match, tableBlock) => {
      console.log(`📐 [stripLandscape] Removed landscape wrapper around table (prevents page break)`);
      return tableBlock;
    }
  );
}

/**
 * Auto-fit wide tables using scaling — NO landscape, NO page breaks.
 *
 * Strategy by column count:
 *   4-6 cols: \small font only (usually fits)
 *   7-9 cols: \footnotesize + adjustbox{max width=\textwidth}
 *  10+ cols:  \scriptsize + adjustbox{max width=\textwidth}
 *
 * Tables already wrapped in adjustbox are skipped.
 */
export function autoFitWideTables(latex: string): string {
  return latex.replace(
    /(\\begin\{table\*?\}(?:\[[^\]]*\])?)([\s\S]*?)(\\end\{table\*?\})/g,
    (_match, beginTag, body, endTag) => {
      // Skip if already has adjustbox
      if (body.includes('adjustbox')) return _match;

      const cols = countTableColumns(body);

      // Determine font size + wrapping strategy by column count
      let fontSize: string | null = null;
      if (cols >= 10) {
        fontSize = '\\scriptsize';
      } else if (cols >= 7) {
        fontSize = '\\footnotesize';
      } else if (cols >= 5) {
        fontSize = '\\small';
      }

      if (fontSize) {
        console.log(`📐 [autoFit] Table with ${cols} columns → ${fontSize} + adjustbox`);
        let fitted = body;
        if (fitted.includes('\\centering')) {
          fitted = fitted.replace(/\\centering/, `\\centering${fontSize}`);
        } else {
          fitted = `\\centering${fontSize}\n` + fitted;
        }
        // Wrap the tabular environment in adjustbox (match tabular, tabularx, tabular*)
        fitted = fitted.replace(
          /(\\begin\{tabular[x*]?\})/,
          '\\begin{adjustbox}{max width=\\textwidth}\n$1'
        );
        fitted = fitted.replace(
          /(\\end\{tabular[x*]?\})/,
          '$1\n\\end{adjustbox}'
        );
        return `${beginTag}${fitted}${endTag}`;
      }

      return _match;
    }
  );
}

/**
 * Safety net: wrap any remaining bare tabular environments (not already in
 * adjustbox) with adjustbox to prevent text overflow. Catches ALL tables
 * including those with few columns but long cell content that still overflows.
 * Also catches bare tabular environments outside of \begin{table} wrappers.
 */
export function safetyWrapOverflowTables(latex: string): string {
  // Phase 1: Wrap tabular inside \begin{table} environments
  let result = latex.replace(
    /(\\begin\{table\*?\}(?:\[[^\]]*\])?\s*(?:\\centering\s*)?(?:\\(?:small|footnotesize|scriptsize)\s*)?)([\s\S]*?)(\\end\{table\*?\})/g,
    (match, prefix, body, endTag) => {
      // Skip if already has adjustbox or resizebox
      if (body.includes('adjustbox') || body.includes('resizebox')) return match;
      // Skip if no tabular at all
      if (!/\\begin\{tabular[x*]?\}/.test(body)) return match;

      // Wrap the tabular in adjustbox as a safety net (match tabular, tabularx, tabular*)
      const wrapped = body.replace(
        /(\\begin\{tabular[x*]?\})/,
        '\\begin{adjustbox}{max width=\\textwidth}\n$1'
      ).replace(
        /(\\end\{tabular[x*]?\})/,
        '$1\n\\end{adjustbox}'
      );
      return `${prefix}${wrapped}${endTag}`;
    }
  );

  // Phase 2: Catch bare tabular environments NOT inside a \begin{table} wrapper.
  // These can occur when Claude writes inline tabular blocks in the text.
  result = result.replace(
    /(?<!adjustbox\}[\s\n]*)(\\begin\{tabular[x*]?\}(?:\s*\{[^}]*\})*\s*\{[^}]+\}[\s\S]*?\\end\{tabular[x*]?\})/g,
    (match, tabularBlock) => {
      // Skip if already wrapped in adjustbox (check the 30 chars preceding the match)
      if (match.includes('adjustbox')) return match;
      // Only wrap if not already inside adjustbox (the negative lookbehind handles most cases)
      return `\\begin{adjustbox}{max width=\\textwidth}\n${tabularBlock}\n\\end{adjustbox}`;
    }
  );

  return result;
}
