/**
 * Quick heuristic to detect blank/empty PNG images without external dependencies.
 *
 * Strategy: decode raw IDAT (image-data) chunks and check if the uncompressed
 * pixel data has very low variance (= single solid colour → blank figure).
 * Falls back to a simple file-size heuristic when zlib decompression fails.
 *
 * A typical blank 640×480 white PNG at 150 DPI is ~2-6 KB.
 * A figure with actual content is almost always > 15 KB.
 */
export function isBlankPng(buffer: Buffer): boolean {
  try {
    // Very small PNGs (< 4 KB) are almost always blank
    if (buffer.length < 4096) return true;

    // Extract IDAT chunks and decompress
    const idatChunks: Buffer[] = [];
    let offset = 8; // skip PNG signature
    while (offset + 8 < buffer.length) {
      const chunkLen = buffer.readUInt32BE(offset);
      const chunkType = buffer.toString('ascii', offset + 4, offset + 8);
      if (chunkType === 'IDAT') {
        idatChunks.push(buffer.subarray(offset + 8, offset + 8 + chunkLen));
      }
      offset += 12 + chunkLen; // length + type + data + CRC
    }

    if (idatChunks.length === 0) return true;

    const { inflateSync } = require('zlib') as typeof import('zlib');
    const raw = inflateSync(Buffer.concat(idatChunks));

    // Sample up to 10 000 bytes from the decompressed pixel data
    const sampleSize = Math.min(raw.length, 10000);
    let sum = 0;
    let sumSq = 0;
    for (let i = 0; i < sampleSize; i++) {
      const v = raw[i];
      sum += v;
      sumSq += v * v;
    }
    const mean = sum / sampleSize;
    const variance = sumSq / sampleSize - mean * mean;
    // Very low variance → all pixels essentially the same → blank
    if (variance < 50) return true;

    return false;
  } catch {
    // If anything goes wrong, don't block the figure — include it
    return false;
  }
}

